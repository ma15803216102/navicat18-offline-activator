# -*- coding: utf-8 -*-
"""生成一套属于你自己的 RSA-2048 密钥对，并产出构建离线版所需的 C# 源码。

用法：
    python tools/gen_keys.py [--force]

产物：
    keys/mykey_priv.pem   ← 私钥（绝不要提交/外传；已在 .gitignore 里）
    keys/mykey_pub.pem    ← 公钥（可以公开）
    src/pem_local.cs      ← 公钥 PEM 的 C# 字节数组（构建时被编进 exe，用于替换 navicat.exe 里的请求码公钥）

为什么需要这一步：
    本工具的原理是「用自己的密钥对替换 Navicat 内嵌的请求码公钥/验签模数」。
    仓库里不含任何人的私钥，每人自己生成一对即可离线签发。
    私钥一旦泄露 = 任何人都能给自己签发激活码；请勿提交到 Git。
"""
import argparse
import io
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
KEYS = os.path.join(ROOT, 'keys')
PRIV = os.path.join(KEYS, 'mykey_priv.pem')
PUB = os.path.join(KEYS, 'mykey_pub.pem')
OUT = os.path.join(ROOT, 'src', 'pem_local.cs')

PEM_BEGIN = '-----BEGIN PUBLIC KEY-----'
PEM_END = '-----END PUBLIC KEY-----'


def find_openssl():
    cands = [
        'openssl',
        r'D:\software\Git\usr\bin\openssl.exe',
        r'C:\Program Files\Git\usr\bin\openssl.exe',
        r'C:\Program Files (x86)\Git\usr\bin\openssl.exe',
    ]
    for c in cands:
        try:
            r = subprocess.run([c, 'version'], capture_output=True, text=True, timeout=10)
            if r.returncode == 0 and 'OpenSSL' in (r.stdout or ''):
                return c
        except Exception:
            pass
    return None


def gen_with_cryptography():
    try:
        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric import rsa
    except Exception:
        return False
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    priv = key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption())
    pub = key.public_key().public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo)
    io.open(PRIV, 'wb').write(priv)
    io.open(PUB, 'wb').write(pub)
    return True


def gen_with_openssl():
    ossl = find_openssl()
    if not ossl:
        return False
    r = subprocess.run([ossl, 'genrsa', '-out', PRIV, '2048'],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        return False
    r = subprocess.run([ossl, 'rsa', '-in', PRIV, '-pubout', '-out', PUB],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        return False
    return True


def spki_pem_460(pub_path):
    """读出公钥 PEM，统一成 Navicat 里那种 CRLF 行尾、460 字节的 SPKI PEM。"""
    raw = io.open(pub_path, 'r', encoding='ascii').read()
    lines = [ln.strip() for ln in raw.replace('\r', '').split('\n') if ln.strip()]
    if not lines or lines[0] != PEM_BEGIN or lines[-1] != PEM_END:
        raise SystemExit('公钥 PEM 格式异常（缺少 BEGIN/END 行）')
    body = ''.join(lines[1:-1])
    # 按 64 字符重排（OpenSSL 默认就是 64，这里保证一致）
    chunks = [body[i:i + 64] for i in range(0, len(body), 64)]
    text = '\r\n'.join([PEM_BEGIN] + chunks + [PEM_END]) + '\r\n'
    data = text.encode('ascii')
    if len(data) != 460:
        raise SystemExit('公钥 PEM 长度为 %d 字节，Navicat 要求 460 字节（RSA-2048 SPKI）。' % len(data))
    return data


def carr(name, data, per=16):
    out = ['    internal static readonly byte[] %s = new byte[] {' % name]
    for i in range(0, len(data), per):
        out.append('        ' + ', '.join('0x%02X' % b for b in data[i:i + per]) + ',')
    out.append('    };')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--force', action='store_true', help='覆盖已存在的密钥')
    args = ap.parse_args()

    if not os.path.isdir(KEYS):
        os.makedirs(KEYS)
    if os.path.exists(PRIV) and not args.force:
        print('已存在 %s，直接复用它（要重新生成请加 --force）。' % PRIV)
    else:
        ok = gen_with_cryptography()
        how = 'cryptography'
        if not ok:
            ok = gen_with_openssl()
            how = 'openssl'
        if not ok:
            raise SystemExit('生成密钥失败：既没有 cryptography 库，也找不到 openssl。')
        print('已生成密钥对（%s）：%s' % (how, KEYS))

    data = spki_pem_460(PUB)
    cs = ('// auto-generated by tools/gen_keys.py -- do not commit\n'
          '// 本文件是本机密钥对的公钥（PEM，460 字节 CRLF），构建时会被替换进 navicat.exe。\n'
          'internal static class PemData\n'
          '{\n' + carr('Pem', data) + '\n}\n')
    io.open(OUT, 'w', encoding='utf-8-sig', newline='').write(cs)
    print('已生成 %s（公钥 %d 字节）' % (OUT, len(data)))
    print('下一步：python tools/gen_offline.py   # 用私钥生成 src/offline.cs')


if __name__ == '__main__':
    main()
