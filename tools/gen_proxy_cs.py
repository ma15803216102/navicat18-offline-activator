# -*- coding: utf-8 -*-
"""把编译好的代理 version.dll 转成 C# 可内嵌的字节数组（XOR 混淆，风格同 pdata.cs）。

用法：
    python tools/gen_proxy_cs.py [--dll bin/version.dll] [--out src/proxy_data.cs]

输出 src/proxy_data.cs（生成物，不入库）。
"""
import argparse
import hashlib
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dll', default=os.path.join(ROOT, 'bin', 'version.dll'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'src', 'proxy_data.cs'))
    args = ap.parse_args()

    if not os.path.exists(args.dll):
        raise SystemExit('找不到 %s（先运行 build\\build_proxy.cmd）' % args.dll)
    data = io.open(args.dll, 'rb').read()
    enc = bytes(x ^ ((0x5A + i * 31) & 0xFF) for i, x in enumerate(data))

    L = []
    L.append('/* auto-generated by tools/gen_proxy_cs.py -- do not edit')
    L.append(' *')
    L.append(' * 「version.dll 方式」用的代理 DLL 字节（XOR 混淆）。安装时释放到 Navicat')
    L.append(' * 安装目录，被 navicat.exe 优先加载（不在 KnownDLLs、exe 同目录优先），')
    L.append(' * 转发 3 个 version 导出给系统 DLL，并在后台线程里完成运行时补丁：')
    L.append(' *   1) 把 navicat.exe 内存映像中的请求码公钥 PEM 换成我们自己的；')
    L.append(' *   2) 按函数序言定位 libcf.dll 的 RSA 解密函数，就地改写为跳到运行时')
    L.append(' *      分配的 shell（shell 替换验签模数后继续执行原逻辑）。')
    L.append(' */')
    L.append('internal static class ProxyData')
    L.append('{')
    L.append('    private static byte[] Dec(byte[] src)')
    L.append('    {')
    L.append('        var r = (byte[])src.Clone();')
    L.append('        for (int i = 0; i < r.Length; i++) r[i] ^= (byte)((0x5A + i * 31) & 0xFF);')
    L.append('        return r;')
    L.append('    }')
    L.append('')
    L.append('    private static readonly byte[] _dll = new byte[] {')
    for i in range(0, len(enc), 16):
        L.append('        ' + ' '.join('0x%02x,' % b for b in enc[i:i + 16]))
    L.append('    };')
    L.append('')
    L.append('    internal static byte[] GetDll() { return Dec(_dll); }')
    L.append('    internal static int Len { get { return _dll.Length; } }')
    L.append('    internal const string Sha256 = "%s";' % hashlib.sha256(data).hexdigest())
    L.append('}')
    L.append('')

    io.open(args.out, 'w', encoding='utf-8-sig', newline='\r\n').write('\n'.join(L))
    print('dll    = %d 字节' % len(data))
    print('sha256 = %s' % hashlib.sha256(data).hexdigest())
    print('out    = %s' % args.out)


if __name__ == '__main__':
    main()
