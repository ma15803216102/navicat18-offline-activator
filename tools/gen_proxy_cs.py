# -*- coding: utf-8 -*-
"""把编译好的代理 version.dll 转成 C# 可内嵌的字节数组。

加密方式：**每次构建随机 pad 的 OTP（pad 与密文分离存放，运行时纯异或还原）**。
    · 不再使用固定 XOR key —— 固定 key 的产物容易被静态特征（YARA/PE 片段）扫到；
    · pad 随机后，同一份 DLL 每次构建出来的字节都不同，签名/特征更难稳定命中。

用法：
    python tools/gen_proxy_cs.py [--dll bin/version.dll] [--out src/proxy_data.cs]

输出 src/proxy_data.cs（生成物，不入库）。
"""
import argparse
import hashlib
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def carr(name, data, per=16):
    out = ['    private static readonly byte[] %s = new byte[] {' % name]
    for i in range(0, len(data), per):
        out.append('        ' + ', '.join('0x%02x' % b for b in data[i:i + per]) + ',')
    out.append('    };')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dll', default=os.path.join(ROOT, 'bin', 'version.dll'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'src', 'proxy_data.cs'))
    args = ap.parse_args()

    if not os.path.exists(args.dll):
        raise SystemExit('找不到 %s（先运行 build\\build_proxy.cmd）' % args.dll)

    data = io.open(args.dll, 'rb').read()
    pad = os.urandom(len(data))
    enc = bytes(a ^ b for a, b in zip(data, pad))

    L = []
    L.append('/* auto-generated by tools/gen_proxy_cs.py -- do not edit')
    L.append(' *')
    L.append(' * 「version.dll 方式」用的代理 DLL 字节。加密：每次构建随机 pad 的 OTP')
    L.append(' * （_pad 与 _enc 分离存放，GetDll() 里纯异或还原）——固定 XOR key 的产物')
    L.append(' * 容易被静态特征扫到，随机 pad 让每次构建的字节都不同。')
    L.append(' *')
    L.append(' * 这个 DLL 只在「启动 Navicat 前的窗口期」被释放到安装目录，')
    L.append(' * 一旦检测到 Navicat 已把它映射进进程，就立刻从磁盘删除（见 ProxyWatch）：')
    L.append(' * 进程内模块继续有效，磁盘上不留常驻的代理 DLL。')
    L.append(' */')
    L.append('internal static class ProxyData')
    L.append('{')
    L.append(carr('_pad', pad))
    L.append('')
    L.append(carr('_enc', enc))
    L.append('')
    L.append('    internal static byte[] GetDll()')
    L.append('    {')
    L.append('        var r = new byte[_enc.Length];')
    L.append('        for (int i = 0; i < r.Length; i++) r[i] = (byte)(_enc[i] ^ _pad[i]);')
    L.append('        return r;')
    L.append('    }')
    L.append('')
    L.append('    internal static int Len { get { return _enc.Length; } }')
    L.append('    internal const string Sha256 = "%s";' % hashlib.sha256(data).hexdigest())
    L.append('}')
    L.append('')

    io.open(args.out, 'w', encoding='utf-8-sig', newline='\r\n').write('\n'.join(L))
    print('dll    = %d 字节' % len(data))
    print('sha256 = %s' % hashlib.sha256(data).hexdigest())
    print('out    = %s' % args.out)


if __name__ == '__main__':
    main()
