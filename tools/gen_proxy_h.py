# -*- coding: utf-8 -*-
"""从 src/pdata.cs 与 src/pem_local.cs 生成编译代理 version.dll 所需的 proxy_data.h。

用法：
    python tools/gen_proxy_h.py [--out bin/proxy_data.h]

proxy_data.h 是「生成物」，不入库；src/version_proxy.c 引用它。
"""
import argparse
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PDATA = os.path.join(ROOT, 'src', 'pdata.cs')
PEMCS = os.path.join(ROOT, 'src', 'pem_local.cs')


def decode_cs_array(text, name, obfuscated):
    m = re.search(r'byte\[\] ' + name + r' = new byte\[\] \{(.*?)\};', text, re.S)
    if not m:
        raise SystemExit('找不到数组 %s' % name)
    raw = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', m.group(1)))
    if obfuscated:
        return bytes(c ^ ((0x5A + i * 31) & 0xFF) for i, c in enumerate(raw))
    return raw


def carr(name, data, per=16):
    lines = ['static const unsigned char %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), per):
        lines.append('    ' + ' '.join('0x%02X,' % b for b in data[i:i + per]))
    lines.append('};')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'bin', 'proxy_data.h'))
    args = ap.parse_args()

    pdata = io.open(PDATA, encoding='utf-8-sig').read()
    shell = decode_cs_array(pdata, '_shell', True)
    pro = decode_cs_array(pdata, '_pro', True)

    if not os.path.exists(PEMCS):
        raise SystemExit('缺少 src/pem_local.cs，请先运行：python tools/gen_keys.py')
    pem = decode_cs_array(io.open(PEMCS, encoding='utf-8-sig').read(), 'Pem', False)
    if len(pem) != 460:
        raise SystemExit('公钥 PEM 长度 %d，应为 460' % len(pem))

    hdr = [
        '/* auto-generated by tools/gen_proxy_h.py -- do not edit */',
        '#ifndef PROXY_DATA_H',
        '#define PROXY_DATA_H',
        '',
        '#define PRO_SIG_LEN   %d' % len(pro),
        '#define SHELL_LEN     %d' % len(shell),
        '#define OUR_PEM_LEN   %d' % len(pem),
        '',
        carr('PRO_SIG', pro),
        '',
        carr('SHELL_CODE', shell),
        '',
        carr('OUR_PEM', pem),
        '',
        '#endif',
        '',
    ]
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    io.open(args.out, 'w', encoding='ascii', newline='\n').write('\n'.join(hdr))
    print('shell=%d pem=%d pro=%d -> %s' % (len(shell), len(pem), len(pro), args.out))


if __name__ == '__main__':
    main()
