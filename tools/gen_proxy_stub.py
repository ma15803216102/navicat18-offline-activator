# -*- coding: utf-8 -*-
"""Write the EMPTY placeholder src/proxy_data.cs (no embedded proxy DLL).

Used by build\\build_offline.cmd when MinGW gcc is unavailable (or the proxy
failed to compile). The exe still builds, but only the libcf.dll mode works:
ProxyData.Available is false and the tool refuses the version.dll mode with a
clear message instead of writing a useless version.dll to Navicat's folder.

The file carries PROXY_STUB_MARKER so that build_offline.cmd retries the real
proxy build on the next run (e.g. after MinGW has been installed).

Usage:
    python tools/gen_proxy_stub.py [--out src/proxy_data.cs]
"""
import argparse
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

BODY = """/* auto-generated by tools/gen_proxy_stub.py -- do not edit
 *
 * PROXY_STUB_MARKER -- EMPTY placeholder, NOT a real proxy DLL.
 *
 * 为什么会有这个文件：构建机上没有 MinGW gcc（或代理 DLL 编译失败）时，
 * 「version.dll 方式」做不出来，但主程序仍然要能编译。这里给出空实现：
 * Available = false，于是工具会明确拒绝该方式并提示改用 libcf.dll，
 * 而不是静默产出一个装上去不生效的 version.dll。
 *
 * 装好 MinGW 后重新跑 build\\build_offline.cmd 即可（脚本看到这个标记会
 * 自动重建真正的代理 DLL 并覆盖本文件）。
 */
internal static class ProxyData
{
    /// <summary>本 exe 是否内嵌了真正的代理 DLL</summary>
    internal static readonly bool Available = false;

    internal static byte[] GetDll() { return new byte[0]; }

    internal static int Len { get { return 0; } }

    internal const string Sha256 = "";
}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'src', 'proxy_data.cs'))
    args = ap.parse_args()

    d = os.path.dirname(os.path.abspath(args.out))
    if d and not os.path.isdir(d):
        os.makedirs(d)
    io.open(args.out, 'w', encoding='utf-8-sig', newline='\r\n').write(BODY)
    print('stub written: %s (ProxyData.Available = false)' % args.out)


if __name__ == '__main__':
    main()
